    private const val PREFS = "quote_state"
    private const val KEY_LAST = "last_index"

    /**
     * 随机挑一条（避开上次启动展示过的），并记住本次的索引。
     * @return 语录与它的索引（索引用于弹窗内「换一句」时排除当前条）
     */
    fun pick(context: Context): Pair<Quote, Int> {
        val prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        val last = prefs.getInt(KEY_LAST, -1)
        var idx = (0 until all.size).random()
        if (all.size > 1 && idx == last) idx = (idx + 1) % all.size
        prefs.edit().putInt(KEY_LAST, idx).apply()
        return all[idx] to idx
    }

    /** 换一条（避开 [exclude]，不写入启动记忆） */
    fun pickAnother(exclude: Int): Pair<Quote, Int> {
        if (all.size <= 1) return all.first() to 0
        var idx = (0 until all.size).random()
        if (idx == exclude) idx = (idx + 1) % all.size
        return all[idx] to idx
    }

    /** 记住当前展示的索引（弹窗内「换一句」后调用，保证下次启动避开它） */
    fun remember(context: Context, idx: Int) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit().putInt(KEY_LAST, idx).apply()
    }
